CREATE TABLE public.medication_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id bigint NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id bigint NOT NULL REFERENCES public.doctors(id),
    nurse_id bigint NOT NULL REFERENCES public.nurses(id),
    medication_name text NOT NULL CHECK (length(btrim(medication_name)) BETWEEN 1 AND 160),
    dose text NOT NULL CHECK (length(btrim(dose)) BETWEEN 1 AND 80),
    route text NOT NULL CHECK (route IN (
        'oral', 'intravenous', 'intramuscular', 'subcutaneous', 'topical',
        'inhaled', 'ophthalmic', 'otic', 'rectal', 'other'
    )),
    scheduled_for timestamp with time zone NOT NULL,
    instructions text CHECK (instructions IS NULL OR length(instructions) <= 500),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'administered', 'held', 'not_given')),
    recorded_by uuid REFERENCES public.user_profiles(id),
    recorded_at timestamp with time zone,
    administration_notes text CHECK (administration_notes IS NULL OR length(administration_notes) <= 500),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX medication_tasks_patient_schedule_idx
    ON public.medication_tasks(patient_id, scheduled_for DESC);
CREATE INDEX medication_tasks_nurse_status_schedule_idx
    ON public.medication_tasks(nurse_id, status, scheduled_for);

ALTER TABLE public.medication_tasks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.medication_tasks FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.get_my_medication_worklist()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_role text;
    v_hospital_id bigint;
    v_doctor_id bigint;
    v_nurse_id bigint;
    v_tasks jsonb;
    v_nurses jsonb;
BEGIN
    SELECT up.role, up.hospital_id
    INTO v_role, v_hospital_id
    FROM public.user_profiles up
    WHERE up.id = auth.uid()
      AND up.status = 'active'
      AND up.role IN ('doctor', 'nurse');

    IF v_role IS NULL OR v_hospital_id IS NULL THEN
        RAISE EXCEPTION 'An active doctor or nurse profile is required.';
    END IF;

    IF v_role = 'doctor' THEN
        SELECT d.id INTO v_doctor_id
        FROM public.doctors d
        WHERE d.user_id = auth.uid()
          AND d.hospital_id = v_hospital_id
          AND d.status = 'active';
        IF v_doctor_id IS NULL THEN
            RAISE EXCEPTION 'An active doctor staff profile is required.';
        END IF;
    ELSE
        SELECT n.id INTO v_nurse_id
        FROM public.nurses n
        WHERE n.user_id = auth.uid()
          AND n.hospital_id = v_hospital_id
          AND n.status = 'active';
        IF v_nurse_id IS NULL THEN
            RAISE EXCEPTION 'An active nurse staff profile is required.';
        END IF;
    END IF;

    SELECT COALESCE(jsonb_agg(to_jsonb(task_rows) ORDER BY task_rows.is_pending DESC, task_rows.scheduled_for, task_rows.id), '[]'::jsonb)
    INTO v_tasks
    FROM (
        SELECT mt.id, mt.patient_id, p.patient_number,
            concat_ws(' ', p.first_name, p.middle_name, p.last_name) AS patient_name,
            mt.medication_name, mt.dose, mt.route, mt.scheduled_for,
            mt.instructions, mt.status, mt.recorded_at, mt.administration_notes,
            nurse_profile.full_name AS nurse_name,
            (mt.status = 'pending') AS is_pending
        FROM public.medication_tasks mt
        JOIN public.patients p ON p.id = mt.patient_id
        JOIN public.nurses n ON n.id = mt.nurse_id AND n.status = 'active'
        JOIN public.user_profiles nurse_profile
          ON nurse_profile.id = n.user_id AND nurse_profile.status = 'active'
        WHERE p.hospital_id = v_hospital_id
          AND (
              (v_role = 'doctor' AND EXISTS (
                  SELECT 1 FROM public.patient_assignments pa
                  WHERE pa.patient_id = mt.patient_id
                    AND pa.doctor_id = v_doctor_id
                    AND pa.status = 'active'
                    AND pa.start_date <= now()
                    AND (pa.end_date IS NULL OR pa.end_date >= now())
              ))
              OR
              (v_role = 'nurse' AND mt.nurse_id = v_nurse_id AND EXISTS (
                  SELECT 1 FROM public.patient_assignments pa
                  WHERE pa.patient_id = mt.patient_id
                    AND pa.nurse_id = v_nurse_id
                    AND pa.status = 'active'
                    AND pa.start_date <= now()
                    AND (pa.end_date IS NULL OR pa.end_date >= now())
              ))
          )
        ORDER BY (mt.status = 'pending') DESC, mt.scheduled_for, mt.id
        LIMIT 200
    ) task_rows;

    IF v_role = 'doctor' THEN
        SELECT COALESCE(jsonb_agg(to_jsonb(nurse_rows) ORDER BY nurse_rows.patient_id, nurse_rows.name), '[]'::jsonb)
        INTO v_nurses
        FROM (
            SELECT DISTINCT pa.patient_id, n.id, nurse_profile.full_name AS name
            FROM public.patient_assignments pa
            JOIN public.patients p ON p.id = pa.patient_id AND p.hospital_id = v_hospital_id
            JOIN public.nurses n ON n.id = pa.nurse_id
              AND n.hospital_id = v_hospital_id AND n.status = 'active'
            JOIN public.user_profiles nurse_profile ON nurse_profile.id = n.user_id
              AND nurse_profile.status = 'active' AND nurse_profile.role = 'nurse'
            WHERE pa.doctor_id = v_doctor_id
              AND pa.status = 'active'
              AND pa.start_date <= now()
              AND (pa.end_date IS NULL OR pa.end_date >= now())
        ) nurse_rows;
    ELSE
        v_nurses := '[]'::jsonb;
    END IF;

    RETURN jsonb_build_object('tasks', v_tasks, 'nurses', v_nurses);
END;
$function$;

REVOKE ALL ON FUNCTION public.get_my_medication_worklist() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_my_medication_worklist() TO authenticated;

CREATE OR REPLACE FUNCTION public.create_medication_task(
    p_patient_id bigint,
    p_nurse_id bigint,
    p_medication_name text,
    p_dose text,
    p_route text,
    p_scheduled_for timestamp with time zone,
    p_instructions text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_hospital_id bigint;
    v_doctor_id bigint;
    v_task_id bigint;
BEGIN
    SELECT up.hospital_id INTO v_hospital_id
    FROM public.user_profiles up
    WHERE up.id = auth.uid() AND up.role = 'doctor' AND up.status = 'active';
    IF v_hospital_id IS NULL THEN
        RAISE EXCEPTION 'An active doctor profile is required.';
    END IF;

    SELECT d.id INTO v_doctor_id
    FROM public.doctors d
    WHERE d.user_id = auth.uid()
      AND d.hospital_id = v_hospital_id
      AND d.status = 'active';
    IF v_doctor_id IS NULL THEN
        RAISE EXCEPTION 'An active doctor staff profile is required.';
    END IF;

    IF p_medication_name IS NULL OR length(btrim(p_medication_name)) NOT BETWEEN 1 AND 160
       OR p_dose IS NULL OR length(btrim(p_dose)) NOT BETWEEN 1 AND 80
       OR p_route IS NULL OR p_route NOT IN (
           'oral', 'intravenous', 'intramuscular', 'subcutaneous', 'topical',
           'inhaled', 'ophthalmic', 'otic', 'rectal', 'other'
       )
       OR p_scheduled_for IS NULL
       OR (p_instructions IS NOT NULL AND length(p_instructions) > 500) THEN
        RAISE EXCEPTION 'Medication task details are invalid.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.patients p
        WHERE p.id = p_patient_id AND p.hospital_id = v_hospital_id
    ) OR NOT EXISTS (
        SELECT 1 FROM public.patient_assignments pa
        WHERE pa.patient_id = p_patient_id
          AND pa.doctor_id = v_doctor_id
          AND pa.status = 'active'
          AND pa.start_date <= now()
          AND (pa.end_date IS NULL OR pa.end_date >= now())
    ) THEN
        RAISE EXCEPTION 'An active assignment to this patient is required.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.nurses n
        JOIN public.user_profiles nurse_profile ON nurse_profile.id = n.user_id
        WHERE n.id = p_nurse_id
          AND n.hospital_id = v_hospital_id
          AND n.status = 'active'
          AND nurse_profile.status = 'active'
          AND nurse_profile.role = 'nurse'
    ) OR NOT EXISTS (
        SELECT 1 FROM public.patient_assignments pa
        WHERE pa.patient_id = p_patient_id
          AND pa.nurse_id = p_nurse_id
          AND pa.status = 'active'
          AND pa.start_date <= now()
          AND (pa.end_date IS NULL OR pa.end_date >= now())
    ) THEN
        RAISE EXCEPTION 'Choose a nurse with an active assignment to this patient.';
    END IF;

    INSERT INTO public.medication_tasks (
        patient_id, doctor_id, nurse_id, medication_name, dose, route,
        scheduled_for, instructions
    ) VALUES (
        p_patient_id, v_doctor_id, p_nurse_id, btrim(p_medication_name),
        btrim(p_dose), p_route, p_scheduled_for, NULLIF(btrim(p_instructions), '')
    ) RETURNING id INTO v_task_id;

    INSERT INTO public.audit_logs (user_id, hospital_id, action, table_name, record_id, description, metadata)
    VALUES (auth.uid(), v_hospital_id, 'medication_task_created', 'medication_tasks', v_task_id,
        'Clinician created a medication dose task.',
        jsonb_build_object('patient_id', p_patient_id, 'nurse_id', p_nurse_id));

    RETURN jsonb_build_object('task_id', v_task_id);
END;
$function$;

REVOKE ALL ON FUNCTION public.create_medication_task(bigint, bigint, text, text, text, timestamp with time zone, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_medication_task(bigint, bigint, text, text, text, timestamp with time zone, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.record_medication_task(
    p_task_id bigint,
    p_status text,
    p_notes text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_hospital_id bigint;
    v_nurse_id bigint;
    v_patient_id bigint;
    v_task_status text;
    v_scheduled_for timestamp with time zone;
BEGIN
    SELECT up.hospital_id INTO v_hospital_id
    FROM public.user_profiles up
    WHERE up.id = auth.uid() AND up.role = 'nurse' AND up.status = 'active';
    IF v_hospital_id IS NULL THEN
        RAISE EXCEPTION 'An active nurse profile is required.';
    END IF;

    SELECT n.id INTO v_nurse_id
    FROM public.nurses n
    WHERE n.user_id = auth.uid()
      AND n.hospital_id = v_hospital_id
      AND n.status = 'active';
    IF v_nurse_id IS NULL THEN
        RAISE EXCEPTION 'An active nurse staff profile is required.';
    END IF;

    IF p_status IS NULL OR p_status NOT IN ('administered', 'held', 'not_given')
       OR (p_notes IS NOT NULL AND length(p_notes) > 500)
       OR (p_status IN ('held', 'not_given') AND NULLIF(btrim(p_notes), '') IS NULL) THEN
        RAISE EXCEPTION 'Choose a valid outcome and provide a reason when a dose is held or not given.';
    END IF;

    SELECT mt.patient_id, mt.status, mt.scheduled_for
    INTO v_patient_id, v_task_status, v_scheduled_for
    FROM public.medication_tasks mt
    JOIN public.patients p ON p.id = mt.patient_id AND p.hospital_id = v_hospital_id
    WHERE mt.id = p_task_id AND mt.nurse_id = v_nurse_id
    FOR UPDATE OF mt;
    IF v_patient_id IS NULL THEN
        RAISE EXCEPTION 'Medication task was not found for this nurse.';
    END IF;
    IF v_task_status <> 'pending' THEN
        RAISE EXCEPTION 'Medication task has already been recorded.';
    END IF;
    IF v_scheduled_for > now() THEN
        RAISE EXCEPTION 'Medication task is not scheduled yet.';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.patient_assignments pa
        WHERE pa.patient_id = v_patient_id
          AND pa.nurse_id = v_nurse_id
          AND pa.status = 'active'
          AND pa.start_date <= now()
          AND (pa.end_date IS NULL OR pa.end_date >= now())
    ) THEN
        RAISE EXCEPTION 'An active assignment to this patient is required.';
    END IF;

    UPDATE public.medication_tasks
    SET status = p_status,
        recorded_by = auth.uid(),
        recorded_at = now(),
        administration_notes = NULLIF(btrim(p_notes), ''),
        updated_at = now()
    WHERE id = p_task_id AND status = 'pending';

    INSERT INTO public.audit_logs (user_id, hospital_id, action, table_name, record_id, description, metadata)
    VALUES (auth.uid(), v_hospital_id, 'medication_task_recorded', 'medication_tasks', p_task_id,
        'Nurse recorded a medication task outcome.',
        jsonb_build_object('patient_id', v_patient_id, 'status', p_status));

    RETURN jsonb_build_object('task_id', p_task_id, 'status', p_status);
END;
$function$;

REVOKE ALL ON FUNCTION public.record_medication_task(bigint, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_medication_task(bigint, text, text) TO authenticated;